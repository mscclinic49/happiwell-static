LIMIT = 1700


def q(v):
    return '$j$' + (v if isinstance(v, str) else json.dumps(v, ensure_ascii=False)) + '$j$'


def chunks(slug, d):
    out, part = [], {}
    def flush():
        if part:
            out.append(f"update public.hw_programs set my = my || {q(dict(part))}::jsonb where slug = '{slug}';")
            part.clear()
    for k, v in d.items():
        trial = dict(part, **{k: v})
        if part and len(json.dumps(trial, ensure_ascii=False).encode()) > LIMIT:
            flush()
        part[k] = v
    flush()
    return out


def sql():
    out = []
    for slug, d in P.items():
        if d:
            out += chunks(slug, d)
    for slug, d in CATS.items():
        out.append(f"update public.hw_program_categories set my = {q(d)}::jsonb where slug = '{slug}';")
    return out


