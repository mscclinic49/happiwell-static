"""รวมคำแปลบทความ (a*.py) กับบทความต้นฉบับ → articles_en.sql
ต้นฉบับ: ไฟล์ JSON ที่ดึงจาก Supabase (hw_articles) ส่งเป็น argument แรก
รัน: python3 supabase/seed/articles_en/build.py <articles.json>
ตรวจว่าจำนวน/ชนิดบล็อกตรงกับภาษาไทยทุกบทความ แล้วเขียน articles_en.sql (อัปเดตคอลัมน์ en)
"""
import json, sys, pathlib, runpy, re
HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
src = {a['slug']: a for a in json.load(open(sys.argv[1]))}
T = {}
for f in sorted(HERE.glob('a[0-9]*.py')):
    T.update(runpy.run_path(str(f))['A'])
errors, out = [], []
for slug, t in T.items():
    a = src.get(slug)
    if not a:
        errors.append(f'{slug}: not in source'); continue
    doc = json.loads(a['content'])
    blocks = doc['blocks']
    if len(blocks) != len(t['blocks']):
        errors.append(f'{slug}: {len(t["blocks"])} blocks, source has {len(blocks)}'); continue
    new = []
    for i, (b, tr) in enumerate(zip(blocks, t['blocks'])):
        b = json.loads(json.dumps(b))
        d = b.setdefault('data', {})
        if tr is None:
            pass
        elif b['type'] == 'list':
            if not isinstance(tr, list) or len(tr) != len(d.get('items', [])):
                errors.append(f'{slug} block {i}: list length mismatch'); continue
            d['items'] = [(x if isinstance(old, str) else {**old, 'content': x}) for x, old in zip(tr, d['items'])]
        elif b['type'] == 'image':
            d['caption'] = tr
        else:
            if not isinstance(tr, str):
                errors.append(f'{slug} block {i}: expected text'); continue
            d['text'] = tr
        # ห้ามมีภาษาไทยหลงเหลือ (ยกเว้นบล็อกที่ตั้งใจคงไว้)
        visible = re.sub(r'href="[^"]*"', '', json.dumps(d, ensure_ascii=False).replace('\\"', '"'))
        if tr is not None and re.search(r'[฀-๿]', visible):
            errors.append(f'{slug} block {i}: Thai text left')
        new.append(b)
    for k in ('title', 'excerpt', 'seo_title', 'seo_description'):
        if re.search(r'[฀-๿]', t.get(k) or ''):
            errors.append(f'{slug}: Thai in {k}')
    en = {k: t[k] for k in ('title', 'excerpt', 'seo_title', 'seo_description')}
    en['content'] = json.dumps({**doc, 'blocks': new}, ensure_ascii=False)
    out.append(f"update public.hw_articles set en = $j${json.dumps(en, ensure_ascii=False)}$j$::jsonb where slug = '{slug}';")
if errors:
    print('\n'.join(errors)); sys.exit(1)
(HERE.parent / 'articles_en.sql').write_text('-- English article translations (column en). Generated by articles_en/build.py\n' + '\n'.join(out) + '\n', encoding='utf-8')
print('ok', len(out), 'articles')

# ---- ไฟล์นำเข้าสำหรับหน้าแอดมิน (/admin-data/en-import.json) ----
progs = runpy.run_path(str(HERE.parent / 'programs_en.py'))
articles_json = {}
for line in out:
    m = re.match(r"update public\.hw_articles set en = \$j\$(.*)\$j\$::jsonb where slug = '([^']+)';$", line, re.S)
    articles_json[m.group(2)] = json.loads(m.group(1))
bundle = {'categories': progs['CATS'], 'programs': progs['P'], 'articles': articles_json}
dest = HERE.parents[2] / 'admin-data' / 'en-import.json'
dest.parent.mkdir(exist_ok=True)
dest.write_text(json.dumps(bundle, ensure_ascii=False), encoding='utf-8')
print('wrote', dest, len(bundle['programs']), 'programs', len(articles_json), 'articles')
